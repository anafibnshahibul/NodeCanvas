function buildGlobalJS(project, pages) {
  return `/* ${project.name} — script.js */
(function(){
  /* Scroll-triggered animations */
  var obs=new IntersectionObserver(function(entries){
    entries.forEach(function(e){
      if(e.isIntersecting){
        var cls=e.target.dataset.ncAnimClass;
        if(cls)e.target.classList.add(cls);
        e.target.style.opacity="1";
        obs.unobserve(e.target);
      }
    });
  },{threshold:0.15});
  document.querySelectorAll("[data-nc-anim-scroll]").forEach(function(el){
    el.style.opacity="0";
    obs.observe(el);
  });

  /* HTMX conditional logic */
  document.addEventListener("htmx:afterRequest",function(e){
    var el=e.detail.elt;
    var ok=e.detail.xhr.status<400;
    var show=ok?el.dataset.ncSuccessShow:el.dataset.ncErrorShow;
    var hide=ok?el.dataset.ncSuccessHide:null;
    if(show)document.querySelector(show)?.classList.remove("hidden");
    if(hide)document.querySelector(hide)?.classList.add("hidden");
  });

  /* Global JS */
  ${project.globalMeta?.globalJS || ""}
})();`;
}

