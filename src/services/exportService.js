// WORDPRESS EXPORT — proper theme with PHP for every page
// ══════════════════════════════════════════════════════════════════════════
async function exportWordPress(project, pages) {
  const id        = uuidv4();
  const slug      = (project.slug || "nodecanvas-theme").replace(/\s+/g,"-").toLowerCase();
  const themeDir  = path.join(EXPORT_DIR, id, slug);
  const zipPath   = path.join(EXPORT_DIR, `${slug}-wp-${id.slice(0,8)}.zip`);

  await fs.mkdir(themeDir, { recursive: true });

  const homepage = pages.find(p => p.isHomepage) || pages[0];
  const innerPages = pages.filter(p => !p.isHomepage);

  // Core theme files
  await fs.writeFile(path.join(themeDir, "style.css"),      buildWPStyleCSS(project));
  await fs.writeFile(path.join(themeDir, "functions.php"),  buildWPFunctions(project, pages));
  await fs.writeFile(path.join(themeDir, "header.php"),     buildWPHeader(project));
  await fs.writeFile(path.join(themeDir, "footer.php"),     buildWPFooter());
  await fs.writeFile(path.join(themeDir, "index.php"),      buildWPIndex(homepage));
  await fs.writeFile(path.join(themeDir, "front-page.php"), buildWPFrontPage(homepage));
  await fs.writeFile(path.join(themeDir, "page.php"),       buildWPPage());
  await fs.writeFile(path.join(themeDir, "single.php"),     buildWPSingle());
  await fs.writeFile(path.join(themeDir, "404.php"),        buildWP404());
  await fs.writeFile(path.join(themeDir, "script.js"),      buildGlobalJS(project, pages));

  // One template-page-[slug].php per non-homepage page
  for (const page of innerPages) {
    const content = buildWPPageTemplate(page, project);
    await fs.writeFile(path.join(themeDir, `template-page-${page.slug}.php`), content);
  }

  await zipDir(path.join(EXPORT_DIR, id), zipPath);
  await fs.rm(path.join(EXPORT_DIR, id), { recursive: true, force: true });
  return zipPath;
}

