// STATIC EXPORT — one HTML file per page
// ══════════════════════════════════════════════════════════════════════════
async function exportStatic(project, pages) {
  const id      = uuidv4();
  const outDir  = path.join(EXPORT_DIR, id);
  const zipPath = path.join(EXPORT_DIR, `${project.slug || "site"}-static-${id.slice(0,8)}.zip`);
  await fs.mkdir(outDir, { recursive: true });

  const globalCSS = buildGlobalCSS(project);
  const globalJS  = buildGlobalJS(project, pages);

  // Write one HTML per page
  for (const page of pages) {
    const filename  = page.isHomepage ? "index.html" : `${page.slug || "page"}.html`;
    const navLinks  = buildNavLinks(pages, page);
    const bodyHTML  = renderNodeToHTML(page.canvas);
    const html      = buildStaticHTML(project, page, navLinks, bodyHTML, pages);
    await fs.writeFile(path.join(outDir, filename), html);
  }

  await fs.writeFile(path.join(outDir, "style.css"),  globalCSS);
  await fs.writeFile(path.join(outDir, "script.js"),  globalJS);

  await zipDir(outDir, zipPath);
  await fs.rm(outDir, { recursive: true, force: true });
  return zipPath;
}

function buildStaticHTML(project, page, navLinks, bodyHTML, pages) {
  const meta     = { ...project.globalMeta, ...page.meta };
  const usesHTMX = bodyHTML ? bodyHTML.includes("hx-") : false;
  return `<!DOCTYPE html>
<html lang="${meta.lang || "en"}">
<head>
  <meta charset="UTF-8"/>
  <meta name="viewport" content="width=device-width,initial-scale=1.0"/>
  <meta name="description" content="${meta.description || ""}"/>
  <title>${meta.title || page.name} — ${project.name}</title>
  <link rel="stylesheet" href="style.css"/>
  ${meta.favicon ? `<link rel="icon" href="${meta.favicon}"/>` : ""}
  ${meta.customHTML || ""}
  ${page.meta?.customCSS ? `<style>${page.meta.customCSS}</style>` : ""}
</head>
<body>
${navLinks ? `<nav style="display:flex;gap:16px;padding:12px 24px;background:#1f2937">${navLinks}</nav>` : ""}
${bodyHTML}
${usesHTMX ? `<script src="https://unpkg.com/htmx.org@2.0.3/dist/htmx.min.js"></script>` : ""}
${buildScrollAnimObserver()}
${meta.customJS || page.meta?.customJS ? `<script>\n${meta.customJS || ""}\n${page.meta?.customJS || ""}\n</script>` : ""}
<script src="script.js"></script>
</body>
</html>`;
}

function buildNavLinks(pages, currentPage) {
  if (pages.length <= 1) return "";
  return pages.map(p => {
    const href = p.isHomepage ? "index.html" : `${p.slug}.html`;
    const active = p._id.toString() === currentPage._id.toString();
    return `<a href="${href}" style="color:${active?"#a78bfa":"#9ca3af"};text-decoration:none;font-size:14px">${p.name}</a>`;
  }).join("");
}

