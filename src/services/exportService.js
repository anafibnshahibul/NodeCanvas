async function exportJSON(project, pages) {
  const id      = uuidv4();
  const outPath = path.join(EXPORT_DIR, `${project.slug || "project"}-${id.slice(0,8)}.json`);
  const payload = { project: { ...project, pages: undefined }, pages };
  await fs.writeFile(outPath, JSON.stringify(payload, null, 2));
  return outPath;
}

// ══════════════════════════════════════════════════════════════════════════
// HTML RENDERER — JSON node tree → clean HTML string
// ══════════════════════════════════════════════════════════════════════════
const VOID_TAGS = new Set(["img","input","br","hr","meta","link","area","base","col","embed","param","source","track","wbr"]);
const STRIP_ATTRS = new Set(["data-nc-id","data-nc-tag","data-nc-container","data-nc-conditional-script","data-nc-anim-trigger","data-nc-container"]);

function renderNodeToHTML(node, depth = 0) {
  if (!node || typeof node !== 'object') return "";
  if (node.type === "text") return node.content || "";

  const tag  = node.tag;
  if (!tag) return "";

  const pad   = "  ".repeat(depth);
  const attrs = buildAttrString(node.attrs || {});

  if (VOID_TAGS.has(tag)) return `${pad}<${tag}${attrs}/>\n`;

  const kids = (node.children || []).map(c => renderNodeToHTML(c, depth + 1)).filter(Boolean).join("");
  return `${pad}<${tag}${attrs}>\n${kids}${pad}</${tag}>\n`;
}

function buildAttrString(attrs) {
  return Object.entries(attrs)
    .filter(([k]) => !STRIP_ATTRS.has(k))
    .map(([k, v]) => ` ${k}="${String(v).replace(/"/g, "&quot;")}"`)
    .join("");
}

// ── Zip helper ─────────────────────────────────────────────────────────
function zipDir(sourceDir, outPath) {
  return new Promise((resolve, reject) => {
    const output  = createWriteStream(outPath);
    const archive = archiver("zip", { zlib: { level: 9 } });
    output.on("close", resolve);
    archive.on("error", reject);
    archive.pipe(output);
    archive.directory(sourceDir, false);
    archive.finalize();
  });
}